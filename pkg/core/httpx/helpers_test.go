package httpx

import "io"

func stringAsBody(s string) io.Reader { return io.NopCloser(&stringReader{s: s}) }

type stringReader struct {
	s string
	i int
}

func (r *stringReader) Read(p []byte) (int, error) {
	if r.i >= len(r.s) {
		return 0, io.EOF
	}
	n := copy(p, r.s[r.i:])
	r.i += n
	return n, nil
}
